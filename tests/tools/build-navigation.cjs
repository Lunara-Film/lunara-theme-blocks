#!/usr/bin/env node
'use strict';
// Deterministic local build. Production serves this committed bundle, not npm.
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'assets/js/lunara-navigation.bundle.js');
const noticesPath = path.join(root, 'assets/js/lunara-navigation.LICENSE.txt');
const notices = ['swup', '@swup/head-plugin', '@swup/plugin', 'delegate-it', 'path-to-regexp'].map(name => {
    const directory = path.join(root, 'node_modules', name);
    const info = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
    const license = ['LICENSE', 'license', 'LICENSE.md'].map(file => path.join(directory, file)).find(fs.existsSync);
    if (!license) throw new Error(`Missing dependency license: ${name}`);
    return `${info.name} ${info.version}\n${fs.readFileSync(license, 'utf8').trim()}\n`;
}).join('\n---\n\n');
const result = esbuild.buildSync({
    entryPoints: [path.join(root, 'assets/js/lunara-navigation.js')],
    bundle: true, write: false, platform: 'browser', format: 'iife',
    target: ['es2020'], minify: true, legalComments: 'inline', charset: 'utf8',
    banner: { js: '/* Generated by tests/tools/build-navigation.cjs. Edit lunara-navigation.js. Swup 4.10.0; Head Plugin 2.3.1. See lunara-navigation.LICENSE.txt. */' }
});
const body = result.outputFiles[0].contents;
const gzip = zlib.gzipSync(body).length;
if (gzip > 30000) throw new Error(`Navigation exceeds its 30 kB gzip ceiling: ${gzip}`);
if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || !fs.readFileSync(output).equals(Buffer.from(body))) throw new Error('The navigation bundle is stale; run node tests/tools/build-navigation.cjs.');
    if (!fs.existsSync(noticesPath) || fs.readFileSync(noticesPath, 'utf8') !== notices) throw new Error('Navigation dependency notices are stale.');
} else { fs.writeFileSync(output, body); fs.writeFileSync(noticesPath, notices); }
console.log(JSON.stringify({ artifact: path.relative(root, output), bytes: body.length, gzipBytes: gzip, checked: process.argv.includes('--check') }));
